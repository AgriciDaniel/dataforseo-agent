#!/usr/bin/env python3
"""Turn the DataForSEO Brain and the endpoint catalog into DataForSEO Agent configuration.

Writes managed files into the app's config folder (default ~/.config/dataforseo-agent):

  dataforseo-agent.json    managed settings: instructions, skills, agents, permissions, MCP server
  dataforseo-agent.jsonc   your own overrides, created empty once and never touched again
  DATAFORSEO.md            the agent brief, loaded as an instruction on every turn
  agents/<name>.md         main agent "dataforseo", "cost-guard", one specialist per API module
  skills/<id>/SKILL.md     one skill per Brain workflow
  commands/<name>.md       /dfs-route, /dfs-cost, /dfs-balance, /dfs-endpoint

Inputs (contract agreed with the Brain and catalog owners, see PLAN.md):

  Brain/wiki/hot.md, cost/*.md, platform/*.md     always-loaded instructions
  Brain/wiki/routing/which-api-for-which-job.md   the router the main agent reads first
  Brain/wiki/modules/<id>.md                      frontmatter module, agent_description
  Brain/wiki/workflows/<id>.md                    frontmatter skill, description, modules
  research/endpoints.json                         {"checked", "endpoints": [{path, method, module, mode,
                                                  purpose, params_required, params_key, limits, price, docs}]}

Every managed file carries the MANAGED marker. Files without it are left alone, so anything
added by hand to agents/, skills/ or commands/ survives a re-run.

Usage: bridge.py --brain <Brain folder> --catalog <endpoints.json> [--config <config folder>]
"""

import argparse
import json
import os
import re
from pathlib import Path

MANAGED = "<!-- dataforseo-agent:managed (regenerated by tools/bridge.py; edit the Brain instead) -->"
APP = "dataforseo-agent"
MAIN = "dataforseo"

MODULE_NAMES = {
    "serp": "SERP",
    "keywords-data": "Keywords Data",
    "labs": "DataForSEO Labs",
    "backlinks": "Backlinks",
    "onpage": "OnPage",
    "domain-analytics": "Domain Analytics",
    "content-analysis": "Content Analysis",
    "content-generation": "Content Generation",
    "business-data": "Business Data",
    "merchant": "Merchant",
    "app-data": "App Data",
    "ai-optimization": "AI Optimization",
    "databases": "Databases",
    "appendix": "Appendix",
}

# DataForSEO deck palette, cycled across specialists.
COLORS = ["#2862A8", "#137A74", "#EABD59", "#5590D8", "#3AABA1", "#D1A54A", "#7AAAE6", "#5CC7BD"]


def split(path: Path):
    text = path.read_text(encoding="utf-8")
    meta = {}
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            for line in text[4:end].splitlines():
                m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
                if m:
                    value = m.group(2).strip().strip('"').strip("'")
                    if value.startswith("[") and value.endswith("]"):
                        value = [v.strip().strip('"').strip("'") for v in value[1:-1].split(",") if v.strip()]
                    meta[m.group(1)] = value
            text = text[end + 4 :]
    # Obsidian embeds mean nothing in a terminal; wikilinks become plain note names.
    text = re.sub(r"!\[\[[^\]]*\]\]\n?", "", text)
    text = re.sub(r"\[\[([^\]|#]+)(?:#[^\]|]*)?\|([^\]]+)\]\]", r"\2", text)
    text = re.sub(r"\[\[([^\]|#]+)(?:#[^\]|]*)?\]\]", r"`\1`", text)
    return meta, text.strip()


def front(fields: dict) -> str:
    return "---\n" + "".join(f"{k}: {json.dumps(v)}\n" for k, v in fields.items()) + "---\n\n" + MANAGED + "\n\n"


def write(path: Path, content: str, written: set):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    written.add(path.resolve())


def prune(folder: Path, written: set):
    if not folder.exists():
        return
    for file in folder.rglob("*.md"):
        if file.resolve() not in written and MANAGED in file.read_text(encoding="utf-8", errors="ignore"):
            file.unlink()
            if file.parent != folder and not any(file.parent.iterdir()):
                file.parent.rmdir()


def price_text(price) -> str:
    if not isinstance(price, dict):
        return "see docs"
    usd = price.get("usd")
    unit = (price.get("unit") or "").replace("_", " ")
    note = price.get("note") or ""
    if usd is None:
        return note or "not published"
    text = f"${usd:g} {unit}".strip()
    return f"{text} ({note})" if note else text


def short(text: str, limit: int = 110) -> str:
    text = re.sub(r"^The purpose of (the )?[^.]*? endpoint is to ", "", (text or "").strip())
    text = text.split(". ")[0].rstrip(".").replace("|", "/")
    text = text[:1].upper() + text[1:]
    return text if len(text) <= limit else text[: limit - 3].rstrip() + "..."


def endpoint_table(endpoints: list, purpose: bool = True) -> str:
    head = ["| Endpoint | Mode | Price |", "|---|---|---|"] if not purpose else ["| Endpoint | Mode | Purpose | Price |", "|---|---|---|---|"]
    rows = list(head)
    for e in sorted(endpoints, key=lambda e: e.get("path", "")):
        cells = [f"`{e.get('method', 'POST')} {e.get('path')}`", e.get("mode", "")]
        if purpose:
            cells.append(short(e.get("purpose")))
        cells.append(price_text(e.get("price")).replace("|", "/"))
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def endpoint_details(endpoints: list) -> str:
    out = []
    for e in sorted(endpoints, key=lambda e: e.get("path", "")):
        bits = [f"### `{e.get('method', 'POST')} {e.get('path')}` ({e.get('mode', '')})", short(e.get("purpose"), 400)]
        if e.get("params_required"):
            bits.append("Required: " + ", ".join(f"`{p}`" for p in e["params_required"]))
        if e.get("params_key"):
            bits.append("Key optional: " + ", ".join(f"`{p}`" for p in e["params_key"]))
        if e.get("limits"):
            bits.append(f"Limits: {e['limits']}")
        price = e.get("price") or {}
        bits.append(f"Price: {price_text(price)}")
        for t in price.get("tiers") or []:
            bits.append(f"- {t.get('mode', '')}: {t.get('price_usd', '')} {t.get('billing_unit', '')}".rstrip())
        if e.get("response_key_fields"):
            bits.append("Key response fields: " + ", ".join(f"`{f}`" for f in e["response_key_fields"]))
        if e.get("note"):
            # Live-tested corrections (real billing, required ids, retired paths) the agent must see.
            bits.append(f"Note: {e['note']}")
        sv = e.get("sandbox_verified")
        if isinstance(sv, dict) and sv.get("pass"):
            bits.append(f"Sandbox verified {sv.get('date', '')}: the example below returned status 20000.")
        if e.get("example") is not None:
            bits.append("Example body" + (f" ({e['example_source']})" if e.get("example_source") else "") + ":\n```json\n" + json.dumps(e["example"], indent=1) + "\n```")
        if e.get("docs"):
            bits.append(f"Docs: {e['docs']}")
        out.append("\n".join(b for b in bits if b))
    return "\n\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--brain", required=True)
    ap.add_argument("--catalog", required=True)
    ap.add_argument("--login-env", default="DATAFORSEO_LOGIN", help="environment variable that holds the DataForSEO login (DATAFORSEO_USERNAME also works)")
    ap.add_argument("--config", default=os.path.join(os.environ.get("XDG_CONFIG_HOME", os.path.expanduser("~/.config")), APP))
    args = ap.parse_args()

    brain = Path(args.brain).resolve()
    wiki = brain / "wiki"
    catalog_path = Path(args.catalog).resolve()
    config = Path(args.config)
    written: set = set()

    catalog = json.loads(catalog_path.read_text(encoding="utf-8")) if catalog_path.exists() else {"endpoints": []}
    endpoints = catalog.get("endpoints", [])
    checked = catalog.get("checked", "unknown")
    by_module: dict = {}
    for e in endpoints:
        by_module.setdefault(e.get("module", "other"), []).append(e)

    # Specialists: one per module note that exists, falling back to catalog modules.
    modules = {}
    for note in sorted((wiki / "modules").glob("*.md")) if (wiki / "modules").exists() else []:
        meta, text = split(note)
        mid = meta.get("module") or note.stem
        modules[mid] = (meta, text, note)
    for mid in by_module:
        if mid not in modules and mid in MODULE_NAMES and mid != "appendix":
            modules[mid] = ({}, "", None)

    agents = config / "agents"
    roster = []
    for i, (mid, (meta, text, note)) in enumerate(sorted(modules.items())):
        name = MODULE_NAMES.get(mid, mid)
        desc = meta.get("agent_description") or f"Use for the DataForSEO {name} API: picking endpoints, building requests, reading results."
        eps = by_module.get(mid, [])
        parts = [
            f"You are the {name} specialist inside DataForSEO Agent. You know every {name} endpoint below: what it returns, "
            "its parameters, its mode (live, task, standard) and its price. Pick the cheapest endpoint and mode that answers the job, "
            "state the expected cost before any paid call, and hand cost questions you cannot settle to @cost-guard.",
        ]
        if note:
            parts.append(f"Your Brain note is `{note}`. Related notes live under `{wiki}`; read them when the job needs detail.")
        if text:
            parts.append(text)
        if eps:
            ref = config / "catalog" / f"{mid}.md"
            write(ref, f"{MANAGED}\n\n# {name} endpoints ({len(eps)}, checked {checked})\n\n{endpoint_details(eps)}\n", written)
            parts.append(
                f"## Endpoint catalog ({len(eps)} endpoints, checked {checked})\n\n"
                f"Full parameters, limits, price tiers and docs links for every endpoint: `{ref}`. Read the entry before building a request.\n\n"
                + endpoint_table(eps, purpose=len(eps) <= 80)
            )
        else:
            parts.append(
                f"This module has no API endpoints in the catalog (checked {checked}). You advise only and make no API calls. "
                f"Use your Brain note, `{wiki}` and https://docs.dataforseo.com/v3/, and say which you used."
            )
        write(agents / f"{mid}.md", front({"description": f"{name}: {desc}", "mode": "all", "color": COLORS[i % len(COLORS)]}) + "\n\n".join(parts) + "\n", written)
        roster.append((mid, name, desc))

    cost_notes = sorted((wiki / "cost").glob("*.md")) if (wiki / "cost").exists() else []
    cost_body = [
        "You are the Cost Guard inside DataForSEO Agent. Before any paid DataForSEO call you estimate the cost from the endpoint "
        "catalog, check it against the approved budget and the account balance (`/v3/appendix/user_data`), and block anything "
        "that is over budget or unapproved. Prefer, in order: no call (answer from the Brain), the free sandbox, Labs databases, "
        "Standard queue, then Live. Show the arithmetic: endpoint, unit price, count, depth or result tier, total.",
        f"Catalog: `{catalog_path}` ({len(endpoints)} endpoints, checked {checked}). Cost notes: `{wiki / 'cost'}`.",
    ]
    for n in cost_notes:
        cost_body.append(split(n)[1])
    write(agents / "cost-guard.md", front({"description": "Cost Guard: Use before any paid DataForSEO call to estimate cost, check balance and budget, and pick the cheapest mode.", "mode": "all", "color": "#EABD59"}) + "\n\n".join(cost_body) + "\n", written)

    team = "\n".join(f"- `@{mid}`: {name}. {desc}" for mid, name, desc in roster)
    router = wiki / "routing" / "which-api-for-which-job.md"
    main_body = f"""You are DataForSEO Agent, the expert for the DataForSEO v3 API. You know every endpoint, its parameters,
its modes and its price, and you turn a user's SEO question into the cheapest correct set of calls.

How you work:
0. Settings: read `{config / "settings.json"}` once per session (create nothing; if it is missing, use budget $1.00,
   always ask, location 2840, language en, mode cheapest). `budget_per_session_usd` is a hard stop: keep a running
   total of billed `tasks[].cost` and refuse a call that would pass it; say how to raise it (`/dfs-settings`).
   Use the default location, language and mode only when the user does not name them, and say which you used.
   Standard queue tasks can take several minutes: say so before posting, and for a one-off lookup the user is
   waiting on, offer Live with both prices. Poll with tasks_ready (free) about once a minute, not with long sleeps.
   `ask_above_usd` only matters for clients without a request prompt.
1. Read the router `{router}` and pick the module and endpoint. When the job is narrow, hand it to the specialist.
2. Before any paid call, state the estimate with its arithmetic and maximum total (ask `@cost-guard` when it is not
   trivial), then make the call in the same turn: the app's request prompt is the approval. Never also ask
   "Run it for $X?" in chat, or the user approves twice. For several paid calls, give the plan total first.
   Free: the sandbox (`https://sandbox.dataforseo.com`), `/v3/appendix/user_data`, locations and languages lists.
   If the user rejects a call at the permission prompt, that is final: do not retry it or rephrase it into another
   call. Stop, say what was not run, and ask what they want instead.
3. The `dataforseo` MCP server (v3) has four tools: `docs_index`, `docs_list_sections`, `docs_search` (free docs lookup)
   and `api_request` (calls any endpoint on api.dataforseo.com, with no cost guard of its own). Price every
   `api_request` from the catalog first. The sandbox is not reachable through it: for free test calls use curl against
   `https://sandbox.dataforseo.com` with credentials from the environment. Never print credentials.
   A paid response is bought once: the script that calls `api_request` must return every field you may need (for
   SERP items: type, rank_group, rank_absolute, domain, url, title, breadcrumb), plus `tasks[].cost` and
   `status_code`. Never repeat a paid call to re-read or re-parse a response; work from what the script returned.
4. Read results critically: check `status_code` (20000 is success) per task, not just the HTTP status, and report cost
   from the response `cost` field. Label it as the billed cost of that call; the list price comes from the catalog,
   and when both appear, name each. Sandbox responses are dummy data: say so whenever you show or chart them.
5. When a task or call returns a non-20000 code, look it up in `{config / "catalog" / "status-codes.md"}` and follow
   its action: retry only when it says so, never resend a paid call blindly.
6. Quote endpoint paths and HTTP methods exactly as the catalog has them. Never write a path that is not in the
   catalog. Before counting requests, take each parameter's maximum (for example `limit`) from the catalog entry.
7. Removed and unavailable endpoints are listed in `{config / "catalog" / "excluded.md"}`. For one of those (or any
   endpoint not in the catalog at all), give its status,
   the reason and the current replacement, then stop: no parameters, no example request.
8. Show results with 3 or more comparable numbers through the `chart` tool. Find the job in "Visuals by workflow"
   below and draw those types first (rules in `platform/visuals.md`). If the user names a different view (for example
   "trend"), draw the defaults first and that view after them. Tables use the listed columns, including any sparkline
   column. Call `chart` once per distinct view; never repeat a spec you already drew. Pass `workflow` (the name in
   that list) on every chart call; the tool rejects views drawn ahead of the defaults unless you give
   `skip_defaults_reason`. When you skip a default, end
   with "Not drawn: <type> (reason)" for each one. Numbers come straight from the response; source = endpoint + actual cost.
   After the chart, give the two or three findings that matter, not a restatement of the numbers. Never retype a
   chart's values in a table of your own; the chart's [table] view already shows them.
9. Write without em dashes or en dashes anywhere, tables included; use commas, colons or parentheses. Leave an empty
   table cell empty (or write "n/a"), never a dash. Never bold a price or a dollar amount.
10. Cite the Brain note or catalog entry for every DataForSEO fact. If the Brain and the catalog disagree, the catalog
   wins; say so.

Specialists:
- `@cost-guard`: estimates and blocks over-budget calls.
{team}

Knowledge:
- Brain: `{wiki}` (Obsidian notes; read on demand).
- Endpoint catalog: `{catalog_path}` ({len(endpoints)} endpoints, checked {checked}).
"""
    write(agents / f"{MAIN}.md", front({"description": "DataForSEO Agent: routes any DataForSEO or SEO data job to the right endpoint, with cost first.", "mode": "all", "color": "#2862A8"}) + main_body, written)
    prune(agents, written)

    # Skills from workflows.
    skills_dir = config / "skills"
    skill_paths = []
    for wf in sorted((wiki / "workflows").glob("*.md")) if (wiki / "workflows").exists() else []:
        meta, text = split(wf)
        sid = meta.get("skill") or wf.stem
        desc = meta.get("description") or f"Use when running the {sid} workflow with DataForSEO."
        mods = meta.get("modules") or []
        extra = f"\nSpecialists for this workflow: {', '.join('@' + m for m in mods)}.\n" if isinstance(mods, list) and mods else ""
        content = f"---\nname: {sid}\ndescription: {json.dumps(desc)}\n---\n\n{MANAGED}\n\nSource note: `{wf}`.{extra}\n{text}\n"
        write(skills_dir / sid / "SKILL.md", content, written)
        skill_paths.append(str(skills_dir / sid))
    prune(skills_dir, written)

    status_path = catalog_path.parent / "status-codes.json"
    if status_path.exists():
        sc = json.loads(status_path.read_text(encoding="utf-8"))
        rows = ["| Code | Class | Meaning | Retry | What to do |", "|---|---|---|---|---|"]
        for c in sc.get("codes", []):
            rows.append("| {} | {} | {} | {} | {} |".format(*(str(c.get(k, "")).replace("|", "/") for k in ("code", "class", "message", "retry", "agent_action"))))
        write(config / "catalog" / "status-codes.md", f"{MANAGED}\n\n# DataForSEO status codes (checked {sc.get('checked', '')})\n\nSource: {sc.get('source', '')}\n\n" + "\n".join(rows) + "\n", written)

    gone = catalog.get("excluded") or []
    gone_mods = catalog.get("modules_without_endpoints") or {}
    if gone or gone_mods:
        lines = [f"{MANAGED}\n\n# Removed, unavailable or non-API DataForSEO surfaces (checked {checked})\n",
                 "Answer questions about these with status, reason and replacement only. No parameters, no example request.\n",
                 "| Path or module | Status | Note | Docs |", "|---|---|---|---|"]
        for g in gone:
            lines.append("| `{} {}` | {} | {} | {} |".format(g.get("method", ""), g.get("path", ""), g.get("status", ""), str(g.get("note", "")).replace("|", "/"), g.get("docs") or ""))
        for m, info in gone_mods.items():
            lines.append(f"| module `{m}` | no endpoints | {str(info.get('note', '')).replace('|', '/')} | {info.get('docs') or ''} |")
        write(config / "catalog" / "excluded.md", "\n".join(lines) + "\n", written)

    commands = config / "commands"
    cmds = {
        "dfs-route": ("Which DataForSEO endpoint fits this job, and what will it cost?", MAIN,
                      f"Route this job to the right DataForSEO module and endpoint, using the router `{router}` and the catalog `{catalog_path}`, with mode and a cost estimate. Do not call any paid endpoint. $ARGUMENTS"),
        "dfs-cost": ("Estimate the cost of a DataForSEO plan before running it", "cost-guard",
                     f"Estimate the cost of this plan from the catalog `{catalog_path}` and show the arithmetic. Do not call any paid endpoint. $ARGUMENTS"),
        "dfs-settings": ("Show or change budget, default market and mode", MAIN,
                         f"Read `{config / 'settings.json'}` and show it as a short table (budget per session, ask above, location, language, mode). If the message asks for a change, write the new value to that file (keep valid JSON, keep the other fields), then show the result. Location codes come from the catalog's locations list; never guess one. Credentials are not in this file: to change them, tell the user to run `dataforseo-agent-setup` in a terminal. $ARGUMENTS"),
        "dfs-balance": ("Show the DataForSEO account balance and limits (free call)", MAIN,
                        "Call `/v3/appendix/user_data` (free) and summarize balance, limits and recent spend. $ARGUMENTS"),
        "dfs-news": ("What changed at DataForSEO lately (free)", MAIN,
                     f"Use the webfetch tool (not web search) on these exact URLs: https://dataforseo.com/feed?post_type=update (official updates feed), "
                     f"https://github.com/dataforseo/mcp-server-typescript/releases.atom (MCP server releases) and "
                     f"https://registry.npmjs.org/dataforseo-mcp-server/latest (current MCP version). Summarize what changed since the catalog date ({checked}), "
                     f"and flag anything that affects endpoints, prices or limits in the catalog `{catalog_path}` or the Brain `{wiki}`. No API calls. $ARGUMENTS"),
        "dfs-endpoint": ("Explain one DataForSEO endpoint: params, modes, price", MAIN,
                         f"Explain this DataForSEO endpoint from the catalog `{catalog_path}` (rendered per module in `{config / 'catalog'}`) and the Brain `{wiki}`: purpose, required and key parameters, modes, limits, price, an example request. If the endpoint is excluded, deprecated or not in the catalog, give its status, reason and replacement, then stop. $ARGUMENTS"),
    }
    for name, (desc, agent, body) in cmds.items():
        write(commands / f"{name}.md", front({"description": desc, "agent": agent}) + body + "\n", written)
    prune(commands, written)
    prune(config / "catalog", written)

    brief = config / "DATAFORSEO.md"
    settings_file = config / "settings.json"
    if not settings_file.exists():
        settings_file.write_text(json.dumps({"budget_per_session_usd": 1.0, "ask_above_usd": 0.0, "default_location_code": 2840,
                                             "default_language_code": "en", "prefer_mode": "cheapest"}, indent=2) + "\n", encoding="utf-8")
    # Default chart types per workflow, so the agent knows them without opening the workflow note.
    visual_index = []
    visual_types = {}
    for wf in sorted((wiki / "workflows").glob("*.md")) if (wiki / "workflows").exists() else []:
        _, text = split(wf)
        m = re.search(r"^## Visuals\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
        if not m:
            continue
        views = []
        for t, rest in re.findall(r"^- `([a-z-]+)`: (.*)$", m.group(1), re.M):
            what = re.sub(r"\s*\([^)]*\)?", "", rest.split(" Fields:")[0].split(".")[0]).strip().rstrip(".")
            if len(what) > 60:
                what = re.sub(r"\s+(and|or|with|of|per|the|a)$", "", what[:60].rsplit(" ", 1)[0].rstrip(","))
            view = f"{t} ({what})"
            if t == "table":
                # Columns: leaf field names from the Fields list, so the agent builds the full table.
                fields = rest.split("Fields:", 1)[1] if "Fields:" in rest else ""
                fields = re.split(r"(?<=[`)])\.(?:\s|$)", fields, maxsplit=1)[0]
                cols = []
                for path, sub in re.findall(r"`([^`]+)`(?:\s*\(([^)]*)\))?", fields):
                    names = [x.strip() for x in sub.split(",")] if sub else [path.split(".")[-1].replace("[]", "")]
                    cols += [n for n in names if n and n not in cols]
                if cols:
                    view += f" [{', '.join(cols)}]"
            spark = re.search(r"sparkline column from ([\w.\[\]]+)", rest)
            if spark:
                view += f" + sparkline column from {spark.group(1)}"
            views.append(view)
        if views:
            visual_index.append(f"- {wf.stem}: " + "; ".join(views))
            visual_types[wf.stem] = [v.split(" ", 1)[0] for v in views]
    visuals_text = ("\nVisuals by workflow (default chart types; full field lists in each workflow note under "
                    f"`{wiki / 'workflows'}`):\n" + "\n".join(visual_index) + "\n") if visual_index else ""
    write(config / "visuals.json", json.dumps(visual_types, indent=1, sort_keys=True) + "\n", written)
    # List prices for the request prompt, so a paid call is never approved without its price.
    prices = {}
    for e in endpoints:
        if e.get("status") != "active" or not e.get("price"):
            continue
        pr = e["price"]
        tier = (pr.get("tiers") or [{}])[0]
        prices[e["path"]] = {"unit": pr.get("unit"), "usd": pr.get("usd"), "price": tier.get("price_usd"),
                             "per": tier.get("billing_unit")}
        # Priority queue price, for task_post bodies that ask for priority 2.
        fast = next((t for t in pr.get("tiers") or [] if "priority" in (t.get("mode") or "").lower()), None)
        amount = re.match(r"\$([0-9.]+)", (fast or {}).get("price_usd") or "")
        if amount:
            prices[e["path"]]["priority_usd"] = float(amount.group(1))
            prices[e["path"]]["priority_price"] = fast["price_usd"]
    write(config / "prices.json", json.dumps(prices, sort_keys=True) + "\n", written)
    command_help = "\n".join(f"- `/{n}`: {b.replace('$ARGUMENTS', '(the rest of the message)')}" for n, (_, _, b) in cmds.items())
    write(brief, MANAGED + "\n\n" + main_body + visuals_text + "\nCommands. In the app these expand automatically. If a message starts with one of them as plain text "
          "(for example in a scripted run), follow its instructions:\n" + command_help + "\n", written)

    instructions = [str(brief)]
    for rel in ["hot.md"]:
        if (wiki / rel).exists():
            instructions.append(str(wiki / rel))
    for folder in ["platform", "cost"]:
        if (wiki / folder).exists():
            instructions += [str(p) for p in sorted((wiki / folder).glob("*.md"))]

    # Spending gate. Every DataForSEO request asks, except endpoints the catalog marks free.
    # Rules are last-match-wins, so the free allowances come after the blanket ask.
    free = set()
    for e in endpoints:
        price = e.get("price") or {}
        if price.get("unit") == "free" or price.get("usd") == 0:
            path = re.sub(r"\{[^}]*\}", "*", e.get("path", ""))
            # Defense in depth: a data purchase path never runs silently, even if the catalog says free.
            if re.search(r"/(live|task_post)(/|$)", path):
                print(f"  warning: not auto-allowing {path}; the catalog marks it free but it looks like a purchase")
                continue
            # Exact canonical path: the engine normalizes every request path to "/v3/...", so no wildcard.
            free.add("/v3" + re.sub(r"^/v3", "", path))
    gate = [{"action": "dataforseo_*", "resource": "*", "effect": "ask"}]
    gate += [{"action": "dataforseo_*", "resource": f, "effect": "allow"} for f in sorted(free)]
    # The docs tools are free.
    gate += [{"action": f"dataforseo_{t}", "resource": "*", "effect": "allow"} for t in ("docs_index", "docs_list_sections", "docs_search")]
    # Raw calls outside the MCP: the live API asks, the sandbox is free.
    gate += [
        {"action": "shell", "resource": "*api.dataforseo.com*", "effect": "ask"},
        {"action": "webfetch", "resource": "*api.dataforseo.com*", "effect": "ask"},
        {"action": "webfetch", "resource": "https://dataforseo.com/*", "effect": "allow"},
        {"action": "webfetch", "resource": "https://docs.dataforseo.com/*", "effect": "allow"},
        {"action": "webfetch", "resource": "https://github.com/dataforseo/*", "effect": "allow"},
        {"action": "webfetch", "resource": "https://registry.npmjs.org/dataforseo-mcp-server*", "effect": "allow"},
    ]

    settings = {
        "default_agent": MAIN,
        "agents": {"build": {"disabled": True}, "plan": {"disabled": True}, "general": {"hidden": True}, "explore": {"hidden": True}},
        "share": "disabled",
        "instructions": instructions,
        "skills": skill_paths,
        "permissions": [
            {"action": "external_directory", "resource": str(brain), "effect": "allow"},
            {"action": "external_directory", "resource": str(brain) + "/*", "effect": "allow"},
            {"action": "external_directory", "resource": str(catalog_path.parent), "effect": "allow"},
            {"action": "external_directory", "resource": str(catalog_path.parent) + "/*", "effect": "allow"},
            {"action": "external_directory", "resource": str(config / "settings.json"), "effect": "allow"},
            {"action": "external_directory", "resource": str(config / "catalog"), "effect": "allow"},
            {"action": "external_directory", "resource": str(config / "catalog") + "/*", "effect": "allow"},
        ]
        + gate,
        "mcp": {
            "servers": {
                # Official DataForSEO MCP server. Credentials come from the user's environment, never from this file.
                "dataforseo": {
                    "type": "local",
                    "command": ["npx", "-y", "dataforseo-mcp-server@3.1.3"],
                    "environment": {
                        "DATAFORSEO_LOGIN": "{env:" + args.login_env + "}",
                        "DATAFORSEO_PASSWORD": "{env:DATAFORSEO_PASSWORD}",
                    },
                    "timeout": {"startup": 120000},
                }
            }
        },
    }
    config.mkdir(parents=True, exist_ok=True)
    (config / f"{APP}.json").write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
    user = config / f"{APP}.jsonc"
    if not user.exists():
        user.write_text("// Your own DataForSEO Agent settings. tools/bridge.py never touches this file.\n{}\n", encoding="utf-8")

    print(f"DataForSEO Agent config written to {config}")
    print(f"  {len(roster) + 2} agents, {len(skill_paths)} skills, {len(cmds)} commands, {len(endpoints)} catalog endpoints, {len(instructions)} instruction files")


if __name__ == "__main__":
    main()
